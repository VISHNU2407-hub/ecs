-- 4. FUNCTIONS
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 4.1 get_app_role() — returns the CURRENT user's authoritative role from
--     public.profiles.role. SECURITY DEFINER so policies can read it without
--     being blocked by profiles RLS. Only ever returns the caller's own role,
--     so exposing it as an RPC is not a leak.
-- ----------------------------------------------------------------------------
create or replace function public.get_app_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role::text
  from public.profiles
  where id = auth.uid()
$$;

-- ----------------------------------------------------------------------------
-- 4.2 can_access_complaint(complaint_id) — visibility rule used by the RLS
--     policies on messages and identity_reveal_requests (the complaint row
--     already exists, so a table lookup is safe there):
--       student   -> only their own complaints
--       faculty   -> non-sensitive complaints (ECS)
--       admin     -> all ECS complaints (coordinator oversight)
--       committee -> sensitive complaints only
--     SECURITY DEFINER: implements the visibility rules itself and never
--     exposes identity columns.
--
--     NOTE: the base `complaints` table does NOT use this function in its
--     SELECT policy. With RLS, INSERT ... RETURNING requires the new row to
--     pass the SELECT policies, and the new row is not in the table yet, so a
--     self-lookup would always evaluate false. `complaints` therefore uses
--     direct, self-referential row policies instead (section 6.3).
-- ----------------------------------------------------------------------------
create or replace function public.can_access_complaint(p_complaint_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select case public.get_app_role()
    when 'student' then exists (
      select 1 from public.complaints c
      where c.id = p_complaint_id and c.student_id = auth.uid()
    )
    when 'faculty' then exists (
      select 1 from public.complaints c
      where c.id = p_complaint_id and c.is_sensitive = false
    )
    when 'admin' then exists (
      select 1 from public.complaints c
      where c.id = p_complaint_id
    )
    when 'committee' then exists (
      select 1 from public.complaints c
      where c.id = p_complaint_id and c.is_sensitive = true
    )
    else false
  end
$$;

-- ----------------------------------------------------------------------------
-- 4.3 handle_new_user() — creates a profile row for every new auth user with
--     the default role 'student'. department_id is left NULL for now: student
--     department membership is implicit (ECS MVP) and faculty/admin department
--     assignment is not configured yet.
-- ----------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role)
  values (new.id, new.email, 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;

-- ----------------------------------------------------------------------------
-- 4.4 derive_complaint_defaults() — BEFORE INSERT on complaints:
--       * ticket_number : CMP-XXXX from an atomic PostgreSQL sequence
--                         (collision-safe under concurrent submissions)
--       * is_sensitive  : always derived from the category (cannot be forged)
--       * handler_type  : committee for sensitive categories, else department
--       * department_id : derived from category_department_map (ECS)
-- ----------------------------------------------------------------------------
create sequence if not exists public.complaints_ticket_seq start 1;

create or replace function public.derive_complaint_defaults()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_category_is_sensitive boolean;
  v_department_id uuid;
begin
  if new.ticket_number is null then
    new.ticket_number := 'CMP-' || lpad(nextval('public.complaints_ticket_seq')::text, 4, '0');
  end if;

  select is_sensitive into v_category_is_sensitive
  from public.complaint_categories
  where id = new.category_id;

  new.is_sensitive := coalesce(v_category_is_sensitive, false);

  if new.is_sensitive then
    new.handler_type := 'committee';
  else
    new.handler_type := 'department';
  end if;

  select department_id into v_department_id
  from public.category_department_map
  where category_id = new.category_id
  limit 1;

  new.department_id := v_department_id;

  return new;
end;
$$;

-- ----------------------------------------------------------------------------
-- 4.5 messages_set_sender() — BEFORE INSERT on messages: the server enforces
--     sender_id = auth.uid() and derives sender_role from the caller's app
--     role, so a client cannot forge who sent a message.
-- ----------------------------------------------------------------------------
create or replace function public.messages_set_sender()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.sender_id := auth.uid();
  new.sender_role := case public.get_app_role()
    when 'student' then 'student'::public.sender_role
    when 'committee' then 'committee'::public.sender_role
    else 'staff'::public.sender_role
  end;
  return new;
end;
$$;

-- ----------------------------------------------------------------------------
-- 4.6 set_updated_at() — keeps complaints.updated_at fresh.
-- ----------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

