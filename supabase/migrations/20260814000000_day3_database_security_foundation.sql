-- ----------------------------------------------------------------------------
-- 2.1 departments — only ECS exists for this MVP. No fake departments.
-- ----------------------------------------------------------------------------
create table if not exists public.departments (
  id         uuid primary key default gen_random_uuid(),
  name       text not null unique,
  created_at timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 2.2 profiles — the authoritative application role lives here.
--     id -> auth.users.id (mirrored by the sign-up trigger).
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id            uuid primary key references auth.users (id) on delete cascade,
  email         text not null,
  role          public.app_role not null default 'student',
  department_id uuid references public.departments (id) on delete set null,
  created_at    timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 2.3 complaint_categories — the eight ECS categories.
--     Harassment / Ragging is sensitive; everything else is not.
-- ----------------------------------------------------------------------------
create table if not exists public.complaint_categories (
  id           uuid primary key default gen_random_uuid(),
  name         text not null unique,
  is_sensitive boolean not null default false,
  created_at   timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 2.4 category_department_map — routing table (category -> department).
--     Keeps routing flexible for future expansion without hardcoding
--     category logic into the departments table.
-- ----------------------------------------------------------------------------
create table if not exists public.category_department_map (
  category_id   uuid not null references public.complaint_categories (id) on delete cascade,
  department_id uuid not null references public.departments (id) on delete cascade,
  primary key (category_id, department_id)
);

-- ----------------------------------------------------------------------------
-- 2.5 complaints — anonymous complaint records. Identity fields are never
--     exposed to staff through the application-facing API (see grants below).
-- ----------------------------------------------------------------------------
create table if not exists public.complaints (
  id             uuid primary key default gen_random_uuid(),
  ticket_number  text not null unique,                    -- CMP-XXXX, sequence-generated
  student_id     uuid not null references public.profiles (id) on delete cascade,
  category_id    uuid not null references public.complaint_categories (id) on delete restrict,
  department_id  uuid references public.departments (id) on delete set null,
  description    text not null,
  attachment_url text,
  priority       public.priority_level not null default 'medium',
  status         public.complaint_status not null default 'submitted',
  handler_type   public.handler_type not null default 'department',
  is_sensitive   boolean not null default false,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 2.6 messages — anonymous complaint messages. sender_id is stored for
--     accountability/audit but is NEVER exposed to application access.
-- ----------------------------------------------------------------------------
create table if not exists public.messages (
  id           uuid primary key default gen_random_uuid(),
  complaint_id uuid not null references public.complaints (id) on delete cascade,
  sender_role  public.sender_role not null,
  sender_id    uuid not null references public.profiles (id) on delete cascade,
  body         text not null,
  created_at   timestamptz not null default now()
);

-- ----------------------------------------------------------------------------
-- 2.7 identity_reveal_requests — student-controlled consent to reveal their
--     identity on a specific complaint. No reveal UI yet (Day 4+).
-- ----------------------------------------------------------------------------
create table if not exists public.identity_reveal_requests (
  id           uuid primary key default gen_random_uuid(),
  complaint_id uuid not null unique references public.complaints (id) on delete cascade,
  status       public.reveal_status not null default 'pending',
  revealed_at  timestamptz,
  revealed_to  uuid references public.profiles (id) on delete set null,
  created_at   timestamptz not null default now()
);

