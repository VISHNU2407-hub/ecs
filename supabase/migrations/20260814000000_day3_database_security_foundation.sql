-- ============================================================================
-- Day 3 — Database, Roles & Security Foundation
-- College Complaint Management System (ECS MVP pilot)
--
-- Run this ONCE in the Supabase SQL editor (or via `supabase db push`).
-- It is idempotent: most statements are guarded so it can be re-run safely,
-- but re-running is not required.
--
-- What this migration creates:
--   * enums          : app_role, priority_level, complaint_status,
--                      handler_type, sender_role, reveal_status
--   * tables         : profiles, departments, complaint_categories,
--                      category_department_map, complaints, messages,
--                      identity_reveal_requests
--   * seed data      : ECS department, the 8 ECS complaint categories,
--                      category -> ECS mapping
--   * functions      : get_app_role, can_access_complaint,
--                      handle_new_user, derive_complaint_defaults,
--                      messages_set_sender, set_updated_at
--   * triggers       : profile auto-creation on sign-up, ticket number
--                      generation, sensitivity/handler/department derivation,
--                      message sender normalization, updated_at
--   * RLS            : enabled on every table + per-role policies
--   * views          : complaints_staff_view, messages_staff_view
--                      (security invoker, identity-free projections)
--   * indexes        : MVP access-pattern indexes
--
-- SECURITY MODEL (summary)
--   * Authoritative role lives ONLY in public.profiles.role. Auth user
--     metadata is never authoritative. A sign-up trigger creates the profile
--     with role 'student'.
--   * Profiles have a select-own-only policy and NO update policy at all:
--     a normal student cannot change role or department_id via the API.
--   * The base complaints/messages tables hide identity COLUMNS
--     (student_id, sender_id) from `authenticated` via column-level grants,
--     and row visibility is controlled by RLS. Staff/admin/committee read
--     complaints through the identity-free staff views, which are
--     security-invoker views so the underlying RLS is respected.
--   * Ticket numbers are generated by a PostgreSQL sequence in a trigger
--     (atomic, collision-safe, CMP-XXXX format).
--   * No secret keys (sb_secret_*) are used anywhere in this migration or
--     in the React app. service_role is never used in frontend code.
-- ============================================================================

