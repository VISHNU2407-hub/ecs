-- ----------------------------------------------------------------------------
-- 6.1 profiles — select-own only. NO insert/update/delete policies at all:
--     the sign-up trigger inserts, and a student can never change their own
--     role or department_id through the API (nor can anyone else).
-- ----------------------------------------------------------------------------
drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own
  on public.profiles
  for select to authenticated
  using (id = auth.uid());

-- ----------------------------------------------------------------------------
-- 6.2 reference data (departments, complaint_categories,
--     category_department_map) — public reference data, no identity inside.
-- ----------------------------------------------------------------------------
drop policy if exists departments_select_all on public.departments;
create policy departments_select_all
  on public.departments
  for select to authenticated
  using (true);

drop policy if exists complaint_categories_select_all on public.complaint_categories;
create policy complaint_categories_select_all
  on public.complaint_categories
  for select to authenticated
  using (true);

drop policy if exists category_department_map_select_all on public.category_department_map;
create policy category_department_map_select_all
  on public.category_department_map
  for select to authenticated
  using (true);

-- ----------------------------------------------------------------------------
-- 6.3 complaints
--     SELECT uses direct, self-referential row policies (see note in 4.2:
--     this keeps INSERT ... RETURNING working for students) and is strictly
--     role-gated — there is NO unrestricted staff SELECT policy:
--       student   -> own rows only (student_id = auth.uid())
--       faculty   -> non-sensitive rows only
--       admin     -> all rows (ECS coordinator oversight)
--       committee -> sensitive rows only
--     INSERT is limited to students creating their own complaint.
--     Identity columns are additionally hidden by column-level grants
--     (section 7), so even a direct query of the base table cannot retrieve
--     student_id.
-- ----------------------------------------------------------------------------
drop policy if exists complaints_select_accessible on public.complaints;
drop policy if exists complaints_select_student on public.complaints;
drop policy if exists complaints_select_faculty on public.complaints;
drop policy if exists complaints_select_admin on public.complaints;
drop policy if exists complaints_select_committee on public.complaints;

create policy complaints_select_student
  on public.complaints
  for select to authenticated
  using (student_id = auth.uid());

create policy complaints_select_faculty
  on public.complaints
  for select to authenticated
  using (public.get_app_role() = 'faculty' and is_sensitive = false);

create policy complaints_select_admin
  on public.complaints
  for select to authenticated
  using (public.get_app_role() = 'admin');

create policy complaints_select_committee
  on public.complaints
  for select to authenticated
  using (public.get_app_role() = 'committee' and is_sensitive = true);

drop policy if exists complaints_insert_own on public.complaints;
create policy complaints_insert_own
  on public.complaints
  for insert to authenticated
  with check (public.get_app_role() = 'student' and student_id = auth.uid());

-- ----------------------------------------------------------------------------
-- 6.4 messages — visibility mirrors the parent complaint. sender_id is
--     enforced by the messages_set_sender trigger and hidden by grants.
-- ----------------------------------------------------------------------------
drop policy if exists messages_select_accessible on public.messages;
create policy messages_select_accessible
  on public.messages
  for select to authenticated
  using (public.can_access_complaint(complaint_id));

drop policy if exists messages_insert_accessible on public.messages;
create policy messages_insert_accessible
  on public.messages
  for insert to authenticated
  with check (public.can_access_complaint(complaint_id));

-- ----------------------------------------------------------------------------
-- 6.5 identity_reveal_requests — the student controls consent: only a
--     student may create or update a reveal request, and only for their own
--     complaint. Other roles can read requests for complaints they can see
--     (the table contains no identity information).
-- ----------------------------------------------------------------------------
drop policy if exists reveal_select_accessible on public.identity_reveal_requests;
create policy reveal_select_accessible
  on public.identity_reveal_requests
  for select to authenticated
  using (public.can_access_complaint(complaint_id));

drop policy if exists reveal_insert_student_own on public.identity_reveal_requests;
create policy reveal_insert_student_own
  on public.identity_reveal_requests
  for insert to authenticated
  with check (public.get_app_role() = 'student' and public.can_access_complaint(complaint_id));

drop policy if exists reveal_update_student_own on public.identity_reveal_requests;
create policy reveal_update_student_own
  on public.identity_reveal_requests
  for update to authenticated
  using (public.get_app_role() = 'student' and public.can_access_complaint(complaint_id))
  with check (public.get_app_role() = 'student' and public.can_access_complaint(complaint_id));

-- ============================================================================
-- 7. GRANTS — defense in depth
--    Strip the broad default grants Supabase applies, then grant exactly the
--    columns each role may touch. Identity columns (student_id, sender_id)
--    are NOT granted to `authenticated`, so even a direct DevTools query of
--    the base tables cannot retrieve them. service_role is left untouched
--    (server-side only, never used by the frontend).
-- ============================================================================

-- 7.0 Strip defaults on every Day 3 table.
revoke all on table public.profiles                 from anon, authenticated;
revoke all on table public.departments              from anon, authenticated;
revoke all on table public.complaint_categories     from anon, authenticated;
revoke all on table public.category_department_map  from anon, authenticated;
revoke all on table public.complaints               from anon, authenticated;
revoke all on table public.messages                 from anon, authenticated;
revoke all on table public.identity_reveal_requests from anon, authenticated;

-- 7.1 profiles — select own only (policies restrict to own row).
grant select (id, email, role, department_id, created_at)
  on public.profiles to authenticated;

-- 7.2 reference data — readable by signed-in users.
grant select on public.departments, public.complaint_categories, public.category_department_map
  to authenticated;

-- 7.3 complaints — SELECT excludes student_id; INSERT limited to the columns
--     a student may set (ticket_number/status/is_sensitive/handler_type/
--     department_id are derived by triggers).
grant select (id, ticket_number, category_id, department_id, description,
              attachment_url, priority, status, handler_type, is_sensitive,
              created_at, updated_at)
  on public.complaints to authenticated;

grant insert (student_id, category_id, description, attachment_url, priority)
  on public.complaints to authenticated;

-- 7.4 messages — SELECT excludes sender_id; INSERT limited to complaint_id +
--     body (sender columns are set by the messages_set_sender trigger).
grant select (id, complaint_id, sender_role, body, created_at)
  on public.messages to authenticated;

grant insert (complaint_id, body)
  on public.messages to authenticated;

-- 7.5 identity_reveal_requests — students may read their own, request a reveal
--     (insert complaint_id only, status always starts 'pending') and change
--     only the status (consent). revealed_at / revealed_to are server-managed.
grant select on public.identity_reveal_requests to authenticated;
grant insert (complaint_id) on public.identity_reveal_requests to authenticated;
grant update (status) on public.identity_reveal_requests to authenticated;

-- ============================================================================
-- 8. SAFE VIEWS (identity-free projections, security invoker so RLS applies)
-- ============================================================================

create or replace view public.complaints_staff_view
with (security_invoker = true)
as
select
  c.id,
  c.ticket_number,
  c.category_id,
  cc.name       as category,
  c.department_id,
  d.name        as department,
  c.description,
  c.attachment_url,
  c.priority,
  c.status,
  c.handler_type,
  c.is_sensitive,
  c.created_at,
  c.updated_at
from public.complaints c
left join public.complaint_categories cc on cc.id = c.category_id
left join public.departments d          on d.id   = c.department_id;

create or replace view public.messages_staff_view
with (security_invoker = true)
as
select
  m.id,
  m.complaint_id,
  m.sender_role,
  m.body,
  m.created_at
from public.messages m;

-- Strip any default grants on the views, then expose them read-only to
-- signed-in users. (Views are created first so the grants can reference them.)
revoke all on table public.complaints_staff_view from anon, authenticated;
revoke all on table public.messages_staff_view   from anon, authenticated;

grant select on public.complaints_staff_view to authenticated;
grant select on public.messages_staff_view   to authenticated;

